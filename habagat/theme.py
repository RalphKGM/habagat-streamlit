def stats(items: Iterable[tuple[int, str, str]]) -> None:
    """Animated count-up strip: (integer value, unit suffix, caption)."""
    def figure(value: int) -> str:
        if value >= 1000:
            return f'<i class="k" style="--tk:{value // 1000};--to:{value % 1000}"></i>'
        return f'<i style="--to:{value}"></i>'

    cells = "".join(
        f'<div class="hb-stat"><div class="num">{figure(int(value))}'
        f'<small>{escape(unit)}</small></div><p>{caption}</p></div>'
        for value, unit, caption in items
    )
    html(f'<div class="hb-stats">{cells}</div>')


def sparkline(values: Sequence[float], color: str, width: int = 300, height: int = 64) -> str:
    lo, hi = min(values), max(values)
    span = (hi - lo) or 1.0
    step = width / (len(values) - 1)
    points = [(i * step, height - 6 - (v - lo) / span * (height - 14)) for i, v in enumerate(values)]
    line = " ".join(f"{x:.1f},{y:.1f}" for x, y in points)
    area = f"M0,{height} L" + " L".join(f"{x:.1f},{y:.1f}" for x, y in points) + f" L{width},{height} Z"
    months = "".join(
        f'<text x="{i * step:.1f}" y="{height - 1}" font-size="8" fill="{INK_SOFT}" '
        f'font-family="JetBrains Mono" text-anchor="{"start" if i == 0 else "end" if i == 11 else "middle"}">{m}</text>'
        for i, m in enumerate("JFMAMJJASOND")
    )
    return (
        f'<svg viewBox="0 0 {width} {height}" preserveAspectRatio="none">'
        f'<path d="{area}" fill="{color}" opacity=".13"/>'
        f'<polyline class="line" points="{line}" fill="none" stroke="{color}" stroke-width="2" '
        f'vector-effect="non-scaling-stroke"/>{months}</svg>'
    )


