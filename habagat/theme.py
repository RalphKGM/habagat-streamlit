def html(markup: str) -> None:
    """Render trusted inline HTML/SVG. st.html strips SVG, so use markdown with
    whitespace collapsed (indented lines would otherwise become code blocks)."""
    st.markdown(" ".join(line.strip() for line in markup.splitlines()), unsafe_allow_html=True)


